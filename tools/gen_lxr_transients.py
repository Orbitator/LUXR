#!/usr/bin/env python3
"""LUXR: the original LXR transient samples as a C header.

  tools/gen_lxr_transients.py OUT.h [--lxr DIR]

Reads mainboard/LxrStm32/src/DSPAudio/transientTables.c of the Sonic Potions LXR firmware
(https://github.com/SonicPotions/LXR) and writes its twelve 8-bit transients (2205 samples each, 44.1 kHz) as
LXR_TRANS[12][2205]. DIR: an LXR checkout ($LXR_SRC, default build/ext/LXR, cloned there when missing).

The samples are not in this repository: they carry the LXR licence (non-commercial, see the header written), which
is not the GPL. A firmware built with them is for personal, non-commercial use and must not be sold or distributed
as a GPL-only work.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
REPO = "https://github.com/SonicPotions/LXR.git"
TABLE = Path("mainboard/LxrStm32/src/DSPAudio/transientTables.c")
NAMES = ["CLK", "CK2", "TIK", "KIK", "RIM", "DRP", "HAT", "CLP", "KK2", "SNR", "TOM", "SP2"]   # the LXR menu's names
N, LEN = 12, 2205


def checkout(arg):
    d = Path(arg or os.environ.get("LXR_SRC") or SRC / "build" / "ext" / "LXR")
    if not (d / TABLE).exists():
        d.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--depth", "1", REPO, str(d)], check=True)
    return d


def parse(text):
    licence = text[:text.index("*/") + 2]
    body = text[text.index("transientData"):]
    body = re.sub(r"//[^\n]*", "", body)
    body = body[body.index("=") + 1:]
    body = body[body.index("{") + 1:]
    rows = re.findall(r"\{([^{}]*)\}", body)[:N]          # one brace block a sample (C pads a short one with zeros)
    tabs = []
    for r in rows:
        vals = [int(v, 0) for v in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", r)]
        if not 2000 < len(vals) <= LEN:
            raise SystemExit(f"gen_lxr_transients: a sample of {len(vals)} values, expected {LEN}")
        vals = [v - 256 if v > 127 else v for v in vals]     # (the table writes them as bytes)
        tabs.append(vals + [0] * (LEN - len(vals)))
    if len(tabs) != N:
        raise SystemExit(f"gen_lxr_transients: {len(tabs)} samples, expected {N}")
    return licence, tabs


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    lxr = checkout(sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "--lxr" else None)
    licence, tabs = parse((lxr / TABLE).read_text(errors="replace"))
    L = ["/* generated by tools/gen_lxr_transients.py from the Sonic Potions LXR firmware: do not edit, do not commit.",
         " * The original LXR transient samples (" + ", ".join(NAMES) + "), signed 8 bit, 44.1 kHz.",
         " * Their licence (LXR, not the GPL): */", licence, "#pragma once", "#include <stdint.h>",
         f"#define LXR_TRANS_N {N}", f"#define LXR_TRANS_LEN {LEN}",
         "static const char *const LXR_TRANS_NAME[LXR_TRANS_N] = {" + ", ".join(f'"{n}"' for n in NAMES) + "};",
         "static const int8_t LXR_TRANS[LXR_TRANS_N][LXR_TRANS_LEN] = {"]
    for t in tabs:
        L.append("{")
        for i in range(0, LEN, 24):
            L.append(" " + ",".join(str(v) for v in t[i:i + 24]) + ",")
        L.append("},")
    L.append("};")
    Path(sys.argv[1]).write_text("\n".join(L) + "\n")
    print(f"lxr transients: {N} x {LEN} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
