"""The LUXR logo for the SYSTEM page (run by tools/build.py generate()).

  gen_logo.py OUT.h [--width 216]

assets/luxr_logo.jpg (light letters and orange marks on black) becomes two 4-bit coverage maps, one per ink:
the letters (drawn in the theme's TEXT, so the logo reads on every palette, light ones too) and the orange marks
with their glow (a fixed orange; MONO: ACCENT). A byte per pixel, letters << 4 | orange, run-length coded as
(count 1..255, byte) pairs, rows back to back. src/lx_ui.c draw_logo decodes it straight into the canvas.
"""
import argparse
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parent.parent / "assets" / "luxr_logo.jpg"


def maps(width):
    im = Image.open(SRC).convert("RGB")
    w0, h0 = im.size
    light, orange = Image.new("L", im.size), Image.new("L", im.size)
    pl, po, px = light.load(), orange.load(), im.load()
    for y in range(h0):
        for x in range(w0):
            r, g, b = px[x, y]
            pl[x, y] = min(255, b * 255 // 225)                      # the letters: their blue (orange has none)
            po[x, y] = max(0, min(255, (r - b) * 255 // 190))        # the marks and their glow: red over blue
    h = round(h0 * width / w0)
    return light.resize((width, h), Image.BOX), orange.resize((width, h), Image.BOX), width, h


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--width", type=int, default=216)
    a = ap.parse_args()
    lm, om, w, h = maps(a.width)
    raw = bytes(((lm.getpixel((x, y)) * 15 + 127) // 255) << 4 | ((om.getpixel((x, y)) * 15 + 127) // 255)
                for y in range(h) for x in range(w))
    rle, i = bytearray(), 0
    while i < len(raw):
        n = 1
        while i + n < len(raw) and n < 255 and raw[i + n] == raw[i]:
            n += 1
        rle += bytes((n, raw[i]))
        i += n
    body = ",".join(str(b) for b in rle)
    Path(a.out).write_text(
        "/* generated by tools/gen_logo.py from assets/luxr_logo.jpg: do not edit */\n"
        f"#define LOGO_W {w}u\n#define LOGO_H {h}u\n"
        f"static const uint8_t LOGO_RLE[{len(rle)}] = {{{body}}};\n")
    print(f"gen_logo: {w} x {h}, {len(rle)} B")


if __name__ == "__main__":
    main()
