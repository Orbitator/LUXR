"""ONE CLICK FM-1: generated tables (oc_tables.h). Fixed point only: the FM-1's CPU has no FPU.
  gen_tables.py OUT.h
"""
import math
import sys

FS = 44100
CTL = 32


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def main(path):
    L = ["/* generated by tools/gen_tables.py: do not edit */", f"#define FS {FS}", f"#define CTL {CTL}"]
    # sine, Q15, 1024 + 1 guard point
    L.append(arr("SINE", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]))
    # phase increment (2^32 / FS) of MIDI note n
    L.append(arr("NOTE_INC", "uint32_t",
                 [min(0xFFFFFFFF, round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS)) for n in range(128)], 6))
    # 2^(k / 192) in Q16 (1/16 semitone steps inside a semitone)
    L.append(arr("FINE16", "uint32_t", [round(65536 * 2 ** (k / 192)) for k in range(16)], 8))
    # cutoff 0..255 -> Chamberlin SVF f = 2 sin(pi fc / (2 FS)) (run twice per sample), Q15; fc 25 Hz .. 16 kHz
    fcs = [25 * (16000 / 25) ** (i / 255) for i in range(256)]
    L.append(arr("SVF_F", "uint16_t", [round(32767 * 2 * math.sin(math.pi * fc / (2 * FS))) for fc in fcs]))
    # envelope: time index 0..127 -> per-block multiplier toward the target (Q16), 1 ms .. 12 s to -60 dB
    times = [0.001 * (12000 ** (i / 127)) for i in range(128)]
    L.append(arr("ENV_K", "uint16_t",
                 [min(65535, round(65536 * math.exp(math.log(0.001) * CTL / FS / t))) for t in times], 8))
    # attack: time index -> Q24 increment per block (linear to full in that time)
    L.append(arr("ATK_INC", "uint32_t", [max(1, round((1 << 24) * CTL / FS / t)) for t in times], 8))
    # TB-303-ish tanh soft clip, 257 points over -2..2 (Q15 in, Q15 out)
    L.append(arr("TANH", "int16_t", [round(32767 * math.tanh(4 * (i - 128) / 256)) for i in range(257)]))
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
