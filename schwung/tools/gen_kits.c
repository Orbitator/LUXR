/* SPDX-License-Identifier: GPL-3.0-only
 * LUXR for Ableton Move (Schwung): the preset kits. Reads a LUXR backup (.luxr: "LUXRBK01", the count, then each
 * slot: its number, its length (4 bytes, little endian), the patch as stored - any LXP format), decodes each patch with
 * the firmware's own code (proj_convert, kit_put: host/lx_host.c) and writes the kits (the eight sounds and the kit's
 * FX, compressor, limiter, master filter) as a C header for the plugin, in their order; the factory kit last.
 *   cc -O1 -Ibuild/gen -Ifirmware/src -o build/gen_kits schwung/tools/gen_kits.c -lm
 *   build/gen_kits web/emu/luxr-backup-....luxr build/gen/luxr_kits.h */
#include "../../host/lx_host.c"

static void put_kit(FILE *f, const char *name)
{
    uint32_t t, j;
    fprintf(f, "    {\"%s\", {\n", name);
    for (t = 0; t < NTRK; t++) {
        const sound_t *s = &snd[t];
        fprintf(f, "        {{");
        for (j = 0; j < 8u; j++)
            fprintf(f, "%u%s", s->p[j], j < 7u ? ", " : "");
        fprintf(f, "}, %u, %u, %u, %u, %u, %d, %d, %u, %u, %u, %u, %u, %d, {{%u, %u, %u, %d}, {%u, %u, %u, %d}}, %u, %u, %u, "
                   "%u, %u, %u},\n",
                s->smp, s->slvl, s->spitch, s->sdec, s->sstart, s->stone, s->sbend, s->syn, s->level, s->dly, s->rev,
                s->drv, s->pan, s->lfo[0].dest, s->lfo[0].wave, s->lfo[0].rate, s->lfo[0].depth, s->lfo[1].dest,
                s->lfo[1].wave, s->lfo[1].rate, s->lfo[1].depth, s->preset, s->och, s->onote, s->atk, s->rel, s->gate);
    }
    fprintf(f, "    }, %d, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %u, %d, %u, %d, "
               "%u, %u, %u, %d},\n",
            song.tune, song.ddec, song.drv_mode, song.drv_amt, song.drv_tone, song.drv_lvl, song.dly_div, song.dly_fb,
            song.dly_tone, song.dly_lvl, song.dly_mode, song.dly_div2, song.rev_size, song.rev_damp, song.rev_lvl,
            song.rev_pre, song.cthr, song.crat, song.catk, song.crel, song.cmak, song.clim, song.lceil, song.lrel,
            song.mflt, song.mres, song.pclip, song.alvl, song.atgt);
}

int main(int argc, char **argv)
{
    static uint8_t buf[1u << 20];
    FILE *in, *f;
    size_t n;
    uint32_t o = 9, k, cnt, nk = 0;
    char name[32];
    if (argc < 3) {
        fprintf(stderr, "usage: gen_kits backup.luxr out.h\n");
        return 2;
    }
    if (!(in = fopen(argv[1], "rb")))
        return perror(argv[1]), 1;
    n = fread(buf, 1, sizeof buf, in);
    fclose(in);
    if (n < 9u || memcmp(buf, "LUXRBK01", 8)) {
        fprintf(stderr, "%s: not a LUXR backup\n", argv[1]);
        return 1;
    }
    host_boot(1);
    if (!(f = fopen(argv[2], "w")))
        return perror(argv[2]), 1;
    fprintf(f, "/* generated by schwung/tools/gen_kits.c from %s: do not edit */\n", argv[1]);
    fprintf(f, "static const lxk_kit_t LXK_KITS[] = {\n");
    cnt = buf[8];
    for (k = 0; k < cnt && o + 5u <= n; k++) {
        uint32_t s = buf[o], len = buf[o + 1] | buf[o + 2] << 8 | (uint32_t)buf[o + 3] << 16 | (uint32_t)buf[o + 4] << 24;
        if (o + 5u + len > n || len > sizeof stage)
            break;
        memcpy(stage, buf + o + 5, len);
        o += 5u + len;
        if (proj_convert(stage, len)) {
            fprintf(stderr, "slot %u: not a patch, left out\n", s + 1u);
            continue;
        }
        kit_put(&proj_buf.k);
        snprintf(name, sizeof name, "Patch %u", s + 1u);
        put_kit(f, name);
        nk++;
    }
    kit_factory();                               /* (the factory kit last: Patch 1 comes first, loaded at the start, as
                                                  * LUXR loads patch 1 at power-on) */
    put_kit(f, "Factory");
    nk++;
    fprintf(f, "};\n#define LXK_NKITS %uu\n", nk);
    fclose(f);
    fprintf(stderr, "gen_kits: %u kits -> %s\n", nk, argv[2]);
    return 0;
}
