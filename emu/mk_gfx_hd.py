"""build/emu/gfx_hd.c: firmware/src/gfx.c with the emulator's HD screen drawn alongside (emu/hd.c).

  mk_gfx_hd.py firmware/src/gfx.c OUT.c

Each edit is a hook after a line of the device's code, which stays as it is; an edit that no longer finds its line
stops the build (gfx.c changed: look at the edit again). The firmware itself never sees this file.
"""
import sys

src, out = sys.argv[1:3]
s = open(src, encoding="utf-8").read()
EDITS = [
    ("static inline uint16_t swap16(uint32_t c) { return (uint16_t)(((c >> 8) & 0xFFu) | ((c & 0xFFu) << 8)); }\n",
     '#include "hd.c"\n'),
    ("    for (i = 0; i < n; i++)\n        cv_px[i] = s;\n}\n", None),            # cv_begin: see below
    ("    lcd_blit(x, y, cv_w, cv_h, cv_px);\n", "    hd_blit(x, y, 0u);\n"),
    ("        lcd_blit(x, y + r0, cv_w, cv_h - r0, cv_px + r0 * cv_w);\n", "    hd_blit(x, y, r0);\n"),
    ("static void cv_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t c)\n{\n", None),
    ("    if (r > h / 2) r = h / 2;\n", "    if (r >= 1) hd_corners(x, y, w, h, r, c, under);\n"),
    ("                cv_alpha(gx, gy, g->bw, g->bh, f->data + g->off, rv);\n",
     "            if (rv) hd_glyph(f, (uint32_t)(g - f->g) >> f->psh, x * 16 + pen, y, rv, gx, gy, g->bw, g->bh);\n"),
    ("    cv_alpha(x, y, k->w, KC_H, KC_DATA + k->off, rv);\n",
     "    hd_keycap(x, y, id < KC_COUNT ? id : 0u, k->w, rv);\n"),
]
for old, add in EDITS:
    if s.count(old) != 1:
        raise SystemExit(f"mk_gfx_hd.py: not found once in {src}: {old!r}")
    if add is None:
        continue
    s = s.replace(old, old + add)
# cv_begin: the HD canvas cleared with it; cv_rect: the HD rectangle first (before it clips its arguments)
s = s.replace("    for (i = 0; i < n; i++)\n        cv_px[i] = s;\n}\n",
              "    for (i = 0; i < n; i++)\n        cv_px[i] = s;\n    hd_begin(w, h, s);\n}\n")
s = s.replace("static void cv_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t c)\n{\n",
              "static void hd_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t c);\n"
              "static void cv_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint16_t c)\n{\n    hd_rect(x, y, w, h, c);\n")
open(out, "w", encoding="utf-8").write("/* generated by emu/mk_gfx_hd.py from firmware/src/gfx.c: do not edit */\n" + s)
