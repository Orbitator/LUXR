"""The emulator's sharp screen: the UI fonts and keycaps rasterised at HD_X times the device's size.

  gen_hd.py OUT.h [--scale 3]

The device draws its 240 x 240 screen with 4-bit glyphs and keycaps (gen_aa_font.py, gen_aa_keycaps.py); the
emulator draws everything a second time at HD_X x (emu/hd.c): rectangles and rounded corners scaled, and the text
and keycaps from these tables, placed by the device's own metrics (pens, kerning, line tops), so the layout stays
the device's. One phase per glyph (at 3 x a third of a device pixel is one HD pixel), no Huffman, no kerning.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import aa_raster as ar           # noqa: E402
import gen_aa_font as gf         # noqa: E402
import gen_aa_keycaps as kc      # noqa: E402


def face(name, spec, px, first, last, extras, lines):
    chars = [chr(c) for c in range(first, last + 1)] + [chr(c) for c in extras]
    r = ar.raster_font(spec, px, chars, 0.0, 1.0, True, 10 ** 6, 1)
    data, table = bytearray(), []
    for ch in chars:
        _, ph = r["glyphs"][ch]
        bx, by, bw, bh, b = ph[0]
        table.append((len(data), bx, by, bw, bh))
        data += b
    lines.append(f"/* {name}: {px} px, asc {r['asc']}, {len(chars)} glyphs, {len(data)} B */")
    lines.append(ar.c_array(f"HD_{name}_DATA", "uint8_t", list(data) + [0, 0], 24, "0x{:02x}"))
    lines.append(f"static const hdg_t HD_{name}_G[{len(table)}] = {{")
    lines += [f"    {{{o}, {bx}, {by}, {bw}, {bh}}}," for o, bx, by, bw, bh in table]
    lines.append("};")
    lines.append(f"static const hdf_t HD_{name} = {{HD_{name}_G, HD_{name}_DATA, {r['asc']}}};")
    return len(data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--scale", type=int, default=3)
    a = ap.parse_args()
    s = a.scale
    lines = ["/* generated by emu/gen_hd.py: the UI's fonts and keycaps at HD_X x for the emulator's screen */",
             "#pragma once", "#include <stdint.h>", f"#define HD_X {s}",
             "typedef struct { uint32_t off; int16_t bx, by; uint16_t bw, bh; } hdg_t;",
             "typedef struct { const hdg_t *g; const uint8_t *data; int32_t asc; } hdf_t;"]
    total = 0
    for name, spec, px, (first, last), extras, _, _ in gf.preset("inter-tight"):
        total += face(name, spec, px * s, first, last, extras, lines)
    # the keycaps: the same pills and labels, every size HD_X x
    kc.KC_PX, kc.KC_H, kc.KC_R, kc.KC_PAD, kc.KC_BASE = kc.KC_PX * s, kc.KC_H * s, kc.KC_R * s, kc.KC_PAD * s, kc.KC_BASE * s
    font = ar.open_font(kc.FONT + f"@{kc.KC_WGHT}", kc.KC_PX)
    data, rows = bytearray(), []
    for _, label in kc.LABELS:
        w, b = kc.keycap(font, label)
        rows.append((len(data), w))
        data += b
    lines.append(f"#define HKC_H {kc.KC_H}")
    lines.append("static const struct { uint32_t off; uint16_t w; } HKC[] = {")
    lines += [f"    {{{o}, {w}}}," for o, w in rows]
    lines.append("};")
    lines.append(ar.c_array("HKC_DATA", "uint8_t", list(data), 24, "0x{:02x}"))
    total += len(data)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"hd: x{s}, {total} B -> {a.out}")


if __name__ == "__main__":
    main()
